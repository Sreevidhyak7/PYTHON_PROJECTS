# EMPTY ARRAY
lst = []
print(type(lst))

st = set()                          #created using set() because {} creates a dict
print(type(st))

tp = ()
print(type(tp))

dt = {}
print(type(dt))


#ONE ELEMENT ARRAYS
lst = [1]
print(type(lst))

st = {1}                          #created using set() because {} creates a dict
print(type(st))

#tp = (1) would create an int data type 
tp = (1,)
print(type(tp))

dt = {"name": "John"}
print(type(dt))
